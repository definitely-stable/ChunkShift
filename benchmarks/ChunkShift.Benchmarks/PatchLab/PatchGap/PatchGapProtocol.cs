internal static class PatchGapToolValidation
{
    internal static void Validate(IEnumerable<PatchGapToolFile> tools)
    {
        PatchGapToolFile[] rows = [.. tools];

        if (rows.Select(static row => row.Id).Distinct(StringComparer.Ordinal).Count() != rows.Length)
        {
            throw new InvalidDataException("tools.json contains duplicate tool ids.");
        }

        foreach (PatchGapToolFile tool in rows)
        {
            if (string.IsNullOrWhiteSpace(tool.Id) ||
                string.IsNullOrWhiteSpace(tool.Version) ||
                string.IsNullOrWhiteSpace(tool.UpstreamCommit) ||
                string.IsNullOrWhiteSpace(tool.ObservedVersion) ||
                string.IsNullOrWhiteSpace(tool.ObservedUpstreamIdentity) ||
                string.IsNullOrWhiteSpace(tool.CreateCommandTemplate) ||
                string.IsNullOrWhiteSpace(tool.ApplyCommandTemplate) ||
                string.IsNullOrWhiteSpace(tool.LogicalArtifact) ||
                string.IsNullOrWhiteSpace(tool.BuildCommand) ||
                string.IsNullOrWhiteSpace(tool.VersionOutput) ||
                Path.IsPathRooted(tool.LogicalArtifact) ||
                tool.ExecutableBytes <= 0)
            {
                throw new InvalidDataException($"Tool '{tool.Id}' has incomplete or host-dependent provenance.");
            }

            if (!string.Equals(tool.Version, tool.ObservedVersion, StringComparison.Ordinal) ||
                !string.Equals(tool.UpstreamCommit, tool.ObservedUpstreamIdentity, StringComparison.Ordinal))
            {
                throw new InvalidDataException($"Tool '{tool.Id}' observed identity differs from its frozen identity.");
            }

            PatchGapEvidence.RequireSha256(tool.SourceArchiveSha256, $"{tool.Id} source/archive SHA-256");
            PatchGapEvidence.RequireSha256(tool.ExecutableOrPackageSha256, $"{tool.Id} executable/package SHA-256");
            PatchGapEvidence.RequireSha256(tool.ExecutableSha256, $"{tool.Id} executable SHA-256");
        }
    }
}

/// <summary>Strict consumer of the merged PATCH-ENC-005 trace/oracle contracts.</summary>
internal static class PatchGapG2Consumer
{
    internal static PatchGapConsumedG2Evidence Read(
        string path,
        string? expectedOracleSampleSha256 = null) =>
        ReadCore(
            path,
            expectedOracleSampleSha256,
            expectedDatasetSha256: null);

    /// <summary>
    /// Uses the same strict schema parser against a caller-supplied dataset lock.
    /// This exists for producer/consumer contract integration tests over a
    /// synthetic corpus; decision evidence must always use <see cref="Read"/>.
    /// </summary>
    internal static PatchGapConsumedG2Evidence ReadContract(
        string path,
        string expectedDatasetSha256,
        string? expectedOracleSampleSha256 = null)
    {
        PatchGapEvidence.RequireSha256(expectedDatasetSha256, "contract dataset SHA-256");
        return ReadCore(
            path,
            expectedOracleSampleSha256,
            expectedDatasetSha256.ToLowerInvariant());
    }

    private static PatchGapConsumedG2Evidence ReadCore(
        string path,
        string? expectedOracleSampleSha256,
        string? expectedDatasetSha256)
    {
        byte[] bytes = File.ReadAllBytes(path);
        using JsonDocument document = JsonDocument.Parse(bytes);
        JsonElement root = document.RootElement;

        if (root.ValueKind != JsonValueKind.Object)
        {
            throw new InvalidDataException("PATCH-ENC-005 evidence root must be an object.");
        }

        string schema = RequiredString(root, "schema");
        return schema switch
        {
            PatchGapProtocol.CandidateTraceSchema => ReadTrace(root, bytes, expectedDatasetSha256),
            PatchGapProtocol.G2OracleSchema => ReadOracle(
                root,
                bytes,
                expectedOracleSampleSha256,
                expectedDatasetSha256),
            _ => throw new InvalidDataException($"Unsupported PATCH-ENC-005 evidence schema '{schema}'."),
        };
    }

    private static PatchGapConsumedG2Evidence ReadTrace(
        JsonElement root,
        byte[] bytes,
        string? expectedDatasetSha256)
    {
        Header header = ReadCommonHeader(
            root,
            requirePlatform: true,
            requireLane: true,
            expectedDatasetSha256);
        string lane = header.Lane!;
        int expectedLevel = PatchGapProtocol.ExpectedTraceFinalLevel(lane);
        int finalLevel = RequiredInt32(root, "finalLevel", minimum: 1);

        if (finalLevel != expectedLevel)
        {
            throw new InvalidDataException(
                $"Trace lane '{lane}' requires finalLevel={expectedLevel}, got {finalLevel}.");
        }

        string family = RequiredNonEmptyString(root, "family");
        if (!string.Equals(PatchGapProtocol.DatasetRole(family), header.DatasetRole, StringComparison.Ordinal))
        {
            throw new InvalidDataException(
                $"Trace family '{family}' does not belong to datasetRole '{header.DatasetRole}'.");
        }

        RequiredNonEmptyString(root, "baseVersion");
        RequiredNonEmptyString(root, "targetVersion");
        string path = RequiredNonEmptyString(root, "path");
        if (path.Contains('\\'))
        {
            throw new InvalidDataException("Candidate trace path must use normalized '/' separators.");
        }

        RequireHex(RequiredString(root, "baseManifestId"), 64, "baseManifestId");
        RequireHex(RequiredString(root, "targetManifestId"), 64, "targetManifestId");

        JsonElement entries = RequiredArray(root, "entries");
        long previousTargetIndex = -1;
        int rowCount = 0;

        foreach (JsonElement entry in entries.EnumerateArray())
        {
            ValidateTraceEntry(entry, finalLevel, ref previousTargetIndex);
            rowCount++;
        }

        return Consumed(header, bytes, lane, oracleSampleSha256: null, rowCount);
    }

    private static PatchGapConsumedG2Evidence ReadOracle(
        JsonElement root,
        byte[] bytes,
        string? expectedOracleSampleSha256,
        string? expectedDatasetSha256)
    {
        Header header = ReadCommonHeader(
            root,
            requirePlatform: false,
            requireLane: false,
            expectedDatasetSha256);

        if (!string.Equals(RequiredString(root, "policy"), PatchGapProtocol.G2OraclePolicy, StringComparison.Ordinal) ||
            !string.Equals(RequiredString(root, "candidateOrder"), PatchGapProtocol.G2OracleCandidateOrder, StringComparison.Ordinal))
        {
            throw new InvalidDataException("The G2 oracle policy/order differs from merged PATCH-ENC-005.");
        }

        string oracleSampleSha256 = RequiredString(root, "oracleSampleSha256");
        RequireHex(oracleSampleSha256, 64, "oracleSampleSha256");

        if (expectedOracleSampleSha256 is null)
        {
            throw new InvalidDataException(
                "G2 oracle consumption requires the pre-materialized oracleSampleSha256 lock.");
        }

        RequireHex(expectedOracleSampleSha256, 64, "expectedOracleSampleSha256");
        if (!string.Equals(
            oracleSampleSha256,
            expectedOracleSampleSha256,
            StringComparison.OrdinalIgnoreCase))
        {
            throw new InvalidDataException(
                $"G2 oracle sample SHA-256 {oracleSampleSha256} does not match locked {expectedOracleSampleSha256}.");
        }

        JsonElement rows = RequiredArray(root, "rows");
        if (rows.GetArrayLength() == 0)
        {
            throw new InvalidDataException("G2 oracle evidence must contain its frozen sampled rows.");
        }

        string? currentPair = null;
        string? previousOrderKey = null;
        var closedPairs = new HashSet<string>(StringComparer.Ordinal);
        int rowCount = 0;
        int pairCount = 0;

        foreach (JsonElement row in rows.EnumerateArray())
        {
            OracleOrder order = ValidateOracleRow(row, header.DatasetRole);

            if (!string.Equals(currentPair, order.PairKey, StringComparison.Ordinal))
            {
                if (currentPair is not null)
                {
                    _ = closedPairs.Add(currentPair);
                }

                if (closedPairs.Contains(order.PairKey))
                {
                    throw new InvalidDataException(
                        "G2 oracle rows re-enter a pair after another pair; sample rows must be contiguous per pair.");
                }

                currentPair = order.PairKey;
                previousOrderKey = null;
                pairCount++;
            }

            if (previousOrderKey is not null &&
                string.CompareOrdinal(previousOrderKey, order.OrderKey) >= 0)
            {
                throw new InvalidDataException(
                    "G2 oracle rows are not in the frozen per-pair sample order or contain duplicates.");
            }

            previousOrderKey = order.OrderKey;
            rowCount++;
        }

        int maximumPairs = header.DatasetRole == "calibration" ? 4 : 8;
        if (pairCount > maximumPairs)
        {
            throw new InvalidDataException(
                $"G2 oracle {header.DatasetRole} evidence contains {pairCount} pairs; frozen maximum is {maximumPairs}.");
        }

        return Consumed(header, bytes, lane: null, oracleSampleSha256, rowCount);
    }

    private static Header ReadCommonHeader(
        JsonElement root,
        bool requirePlatform,
        bool requireLane,
        string? expectedDatasetSha256)
    {
        string experimentId = RequiredNonEmptyString(root, "experimentId");
        if (!string.Equals(experimentId, PatchGapProtocol.PatchEnc005ExperimentId, StringComparison.Ordinal))
        {
            throw new InvalidDataException($"PATCH-GAP only consumes experimentId '{PatchGapProtocol.PatchEnc005ExperimentId}'.");
        }

        string runId = RequiredNonEmptyString(root, "runId");
        string protocolCommit = RequiredString(root, "protocolCommit");
        if (!string.Equals(protocolCommit, PatchGapProtocol.PatchEnc005ProtocolCommit, StringComparison.Ordinal))
        {
            throw new InvalidDataException(
                $"PATCH-GAP only consumes merged PATCH-ENC-005 protocol {PatchGapProtocol.PatchEnc005ProtocolCommit}.");
        }

        string sourceCommit = RequiredString(root, "sourceCommit");
        RequireHex(sourceCommit, 40, "sourceCommit");

        string datasetRole = RequiredNonEmptyString(root, "datasetRole");
        if (!PatchGapProtocol.G2DatasetRoles.Contains(datasetRole))
        {
            throw new InvalidDataException(
                $"PATCH-GAP does not currently consume PATCH-ENC-005 datasetRole '{datasetRole}'.");
        }

        string datasetSha256 = RequiredString(root, "datasetSha256");
        RequireHex(datasetSha256, 64, "datasetSha256");
        string expectedDataset =
            expectedDatasetSha256 ?? PatchGapProtocol.ExpectedG2DatasetSha256(datasetRole);
        if (!string.Equals(datasetSha256, expectedDataset, StringComparison.OrdinalIgnoreCase))
        {
            throw new InvalidDataException(
                $"PATCH-ENC-005 {datasetRole} dataset SHA-256 {datasetSha256} does not match frozen {expectedDataset}.");
        }

        string? platform = requirePlatform ? RequiredNonEmptyString(root, "platform") : OptionalNonEmptyString(root, "platform");
        string? lane = requireLane ? RequiredNonEmptyString(root, "lane") : OptionalNonEmptyString(root, "lane");

        if (requireLane && !PatchGapProtocol.G2ConsumerTraceLanes.Contains(lane!))
        {
            throw new InvalidDataException($"Trace lane '{lane}' is not a frozen PATCH-GAP consumer lane.");
        }

        return new Header(
            experimentId,
            runId,
            protocolCommit,
            sourceCommit.ToLowerInvariant(),
            platform,
            lane,
            datasetRole,
            datasetSha256.ToLowerInvariant());
    }

    private static void ValidateTraceEntry(JsonElement entry, int finalLevel, ref long previousTargetIndex)
    {
        if (entry.ValueKind != JsonValueKind.Object)
        {
            throw new InvalidDataException("Candidate trace entries must be objects.");
        }

        long targetIndex = RequiredInt64(entry, "targetIndex", minimum: 0);
        if (targetIndex <= previousTargetIndex)
        {
            throw new InvalidDataException("Candidate trace targetIndex values must be strictly increasing.");
        }
        previousTargetIndex = targetIndex;

        RequireHex(RequiredString(entry, "targetChunkId"), 64, "targetChunkId");
        _ = RequiredInt64(entry, "targetOffset", minimum: 0);
        int targetLength = RequiredInt32(entry, "targetLength", minimum: 1);
        int candidateCount = RequiredInt32(entry, "candidateCount", minimum: 0);
        int cheapTrials = RequiredInt32(entry, "cheapTrialCount", minimum: 0);
        int expensiveTrials = RequiredInt32(entry, "expensiveTrialCount", minimum: 0);
        int totalTrials = RequiredInt32(entry, "totalCompressionTrialCount", minimum: 1);
        int l19Trials = RequiredInt32(entry, "level19TrialCount", minimum: 0);
        int noDictionary = RequiredInt32(entry, "noDictionaryFrameBytes", minimum: 1);
        int baseline = RequiredInt32(entry, "baselineCostBytes", minimum: 1);
        int stored = RequiredInt32(entry, "storedBytes", minimum: 1);
        int dictionaryRefs = RequiredInt32(entry, "dictionaryRefs", minimum: 0);

        if (baseline != Math.Min(targetLength, noDictionary))
        {
            throw new InvalidDataException("Candidate trace baselineCostBytes is inconsistent.");
        }

        if (totalTrials != 1 + cheapTrials + expensiveTrials)
        {
            throw new InvalidDataException("Candidate trace totalCompressionTrialCount is inconsistent.");
        }

        JsonElement? l19NoDictionary = OptionalProperty(entry, "l19NoDictionaryFrameBytes");
        if (finalLevel == 19)
        {
            if (l19NoDictionary is null ||
                l19NoDictionary.Value.ValueKind != JsonValueKind.Number ||
                l19NoDictionary.Value.GetInt32() != noDictionary ||
                l19Trials != 1 + expensiveTrials)
            {
                throw new InvalidDataException("Candidate trace L19 counters/fields are inconsistent.");
            }
        }
        else if (l19Trials != 0 || (l19NoDictionary is not null && l19NoDictionary.Value.ValueKind != JsonValueKind.Null))
        {
            throw new InvalidDataException("Non-L19 trace contains L19 evidence.");
        }

        JsonElement candidates = RequiredArray(entry, "candidates");
        if (candidates.GetArrayLength() != candidateCount)
        {
            throw new InvalidDataException("candidateCount differs from candidates[].Length.");
        }

        int candidateCheap = 0;
        int candidateFinal = 0;
        int selectedRows = 0;
        int previousOrdinal = -1;
        int? selectedCandidate = OptionalInt32(entry, "selectedCandidate");
        int? selectedRecordCount = null;
        int? selectedFrameBytes = null;

        foreach (JsonElement candidate in candidates.EnumerateArray())
        {
            int ordinal = RequiredInt32(candidate, "ordinal", minimum: 0);
            if (ordinal <= previousOrdinal)
            {
                throw new InvalidDataException("Candidate ordinals must be strictly increasing.");
            }
            previousOrdinal = ordinal;

            _ = RequiredInt32(candidate, "startIndex", minimum: 0);
            _ = RequiredInt64(candidate, "startOffset", minimum: 0);
            int recordCount = RequiredInt32(candidate, "recordCount", minimum: 1);
            if (recordCount > 4)
            {
                throw new InvalidDataException("PATCH-ENC-005 candidate recordCount exceeds frozen K=4.");
            }

            RequireHex(RequiredString(candidate, "firstChunkId"), 64, "firstChunkId");
            string source = RequiredNonEmptyString(candidate, "source");
            if (source is not ("offset" or "sketch" or "both"))
            {
                throw new InvalidDataException($"Unknown candidate source '{source}'.");
            }

            int? cheapLevel = OptionalInt32(candidate, "cheapLevel");
            int? cheapFrame = OptionalInt32(candidate, "cheapFrameBytes");
            int? cheapCost = OptionalInt32(candidate, "cheapCostBytes");
            bool anyCheap = cheapLevel.HasValue || cheapFrame.HasValue || cheapCost.HasValue;
            bool allCheap = cheapLevel.HasValue && cheapFrame.HasValue && cheapCost.HasValue;
            if (anyCheap != allCheap ||
                (allCheap && (cheapLevel != 1 || cheapFrame <= 0 || cheapCost != cheapFrame + (32 * recordCount))))
            {
                throw new InvalidDataException("Candidate cheap-stage fields/cost are inconsistent.");
            }
            if (allCheap)
            {
                candidateCheap++;
            }

            int? finalFrame = OptionalInt32(candidate, "finalFrameBytes");
            int? finalCost = OptionalInt32(candidate, "finalCostBytes");
            bool anyFinal = finalFrame.HasValue || finalCost.HasValue;
            bool allFinal = finalFrame.HasValue && finalCost.HasValue;
            if (anyFinal != allFinal ||
                (allFinal && (finalFrame <= 0 || finalCost != finalFrame + (32 * recordCount))))
            {
                throw new InvalidDataException("Candidate final-stage fields/cost are inconsistent.");
            }
            if (allFinal)
            {
                candidateFinal++;
            }

            int? l19Frame = OptionalInt32(candidate, "l19FrameBytes");
            int? l19Cost = OptionalInt32(candidate, "l19CostBytes");
            if (finalLevel == 19)
            {
                if (l19Frame != finalFrame || l19Cost != finalCost)
                {
                    throw new InvalidDataException("Candidate L19 fields must mirror final fields for an L19 lane.");
                }
            }
            else if (l19Frame.HasValue || l19Cost.HasValue)
            {
                throw new InvalidDataException("Non-L19 trace contains candidate L19 evidence.");
            }

            bool selected = RequiredBoolean(candidate, "selected");
            if (selected)
            {
                selectedRows++;
                if (selectedCandidate != ordinal || !allFinal)
                {
                    throw new InvalidDataException("Selected candidate does not match selectedCandidate/final evidence.");
                }

                selectedRecordCount = recordCount;
                selectedFrameBytes = finalFrame;
            }
        }

        if (candidateCheap != cheapTrials || candidateFinal != expensiveTrials)
        {
            throw new InvalidDataException("Candidate trace trial counters disagree with candidate rows.");
        }

        string encoding = RequiredNonEmptyString(entry, "selectedEncoding");
        switch (encoding)
        {
            case "raw":
                if (selectedCandidate.HasValue || selectedRows != 0 || dictionaryRefs != 0 || stored != targetLength)
                {
                    throw new InvalidDataException("Raw trace winner fields are inconsistent.");
                }
                break;
            case "zstd":
                if (selectedCandidate.HasValue || selectedRows != 0 || dictionaryRefs != 0 || stored != noDictionary)
                {
                    throw new InvalidDataException("No-dictionary zstd trace winner fields are inconsistent.");
                }
                break;
            case "zstd-dictionary":
                if (!selectedCandidate.HasValue || selectedRows != 1 ||
                    selectedRecordCount != dictionaryRefs || selectedFrameBytes != stored)
                {
                    throw new InvalidDataException("Dictionary trace winner fields are inconsistent.");
                }
                break;
            default:
                throw new InvalidDataException($"Unknown selectedEncoding '{encoding}'.");
        }
    }

    private static OracleOrder ValidateOracleRow(JsonElement row, string datasetRole)
    {
        string family = RequiredNonEmptyString(row, "family");
        if (!string.Equals(PatchGapProtocol.DatasetRole(family), datasetRole, StringComparison.Ordinal))
        {
            throw new InvalidDataException(
                $"Oracle family '{family}' does not belong to datasetRole '{datasetRole}'.");
        }
        string baseVersion = RequiredNonEmptyString(row, "baseVersion");
        string targetVersion = RequiredNonEmptyString(row, "targetVersion");
        string path = RequiredNonEmptyString(row, "path");
        if (path.Contains('\\'))
        {
            throw new InvalidDataException("G2 oracle path must use normalized '/' separators.");
        }

        long targetIndex = RequiredInt64(row, "targetIndex", minimum: 0);
        string targetChunkId = RequiredString(row, "targetChunkId");
        RequireHex(targetChunkId, 64, "targetChunkId");
        _ = RequiredInt64(row, "targetOffset", minimum: 0);
        int targetLength = RequiredInt32(row, "targetLength", minimum: 1);
        long enumerated = RequiredInt64(row, "candidateStartsEnumerated", minimum: 0);
        long valid = RequiredInt64(row, "validCandidateCount", minimum: 0);
        if (valid > enumerated)
        {
            throw new InvalidDataException("G2 validCandidateCount exceeds candidateStartsEnumerated.");
        }

        int h0Stored = RequiredInt32(row, "h0StoredBytes", minimum: 1);
        int h0Refs = RequiredInt32(row, "h0DictionaryRefs", minimum: 0);
        long h0Cost = RequiredInt64(row, "h0CostBytes", minimum: 1);
        int oracleStored = RequiredInt32(row, "oracleStoredBytes", minimum: 1);
        int oracleRefs = RequiredInt32(row, "oracleDictionaryRefs", minimum: 0);
        long oracleCost = RequiredInt64(row, "oracleCostBytes", minimum: 1);
        long saved = RequiredInt64(row, "savedBytes", minimum: 0);

        if (h0Cost != h0Stored + ((long)32 * h0Refs) ||
            oracleCost != oracleStored + ((long)32 * oracleRefs) ||
            saved != h0Cost - oracleCost ||
            oracleCost > h0Cost)
        {
            throw new InvalidDataException("G2 oracle cost equation is inconsistent.");
        }

        ValidateWinnerLocation(row, "h0", RequiredNonEmptyString(row, "h0Encoding"), h0Refs, targetLength, h0Stored);
        ValidateWinnerLocation(row, "oracle", RequiredNonEmptyString(row, "oracleEncoding"), oracleRefs, targetLength, oracleStored);

        JsonElement? distance = OptionalProperty(row, "oracleStartDistanceBytes");
        string oracleEncoding = RequiredNonEmptyString(row, "oracleEncoding");
        bool oracleDictionary = oracleEncoding == "zstd-dictionary";
        bool hasDistance = distance.HasValue && distance.Value.ValueKind == JsonValueKind.Number;
        if (oracleDictionary != hasDistance)
        {
            throw new InvalidDataException("oracleStartDistanceBytes nullability disagrees with oracleEncoding.");
        }

        string normalizedChunkId = targetChunkId.ToLowerInvariant();
        string identity = string.Join(
            "\0",
            family,
            baseVersion,
            targetVersion,
            path,
            normalizedChunkId,
            targetIndex.ToString(CultureInfo.InvariantCulture));
        string digest = Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(identity)));
        string pairKey = string.Join("\0", family, baseVersion, targetVersion);
        return new OracleOrder(pairKey, $"{digest}\0{path}\0{targetIndex:D20}");
    }

    private static void ValidateWinnerLocation(
        JsonElement row,
        string prefix,
        string encoding,
        int refs,
        int targetLength,
        int storedBytes)
    {
        int? startIndex = OptionalInt32(row, prefix + "StartIndex");
        long? startOffset = OptionalInt64(row, prefix + "StartOffset");
        int? recordCount = OptionalInt32(row, prefix + "RecordCount");
        string? firstChunkId = OptionalString(row, prefix + "FirstChunkId");
        bool hasAny = startIndex.HasValue || startOffset.HasValue || recordCount.HasValue || firstChunkId is not null;

        switch (encoding)
        {
            case "raw":
                if (refs != 0 || storedBytes != targetLength || hasAny)
                {
                    throw new InvalidDataException($"{prefix} raw winner fields are inconsistent.");
                }
                break;
            case "zstd":
                if (refs != 0 || hasAny)
                {
                    throw new InvalidDataException($"{prefix} no-dictionary winner fields are inconsistent.");
                }
                break;
            case "zstd-dictionary":
                if (refs <= 0 || refs > 4 ||
                    startIndex is null || startIndex < 0 ||
                    startOffset is null || startOffset < 0 ||
                    recordCount != refs ||
                    firstChunkId is null)
                {
                    throw new InvalidDataException($"{prefix} dictionary winner location is incomplete.");
                }

                RequireHex(firstChunkId, 64, prefix + "FirstChunkId");
                break;
            default:
                throw new InvalidDataException($"Unknown {prefix}Encoding '{encoding}'.");
        }
    }

    private static PatchGapConsumedG2Evidence Consumed(
        Header header,
        byte[] bytes,
        string? lane,
        string? oracleSampleSha256,
        int rowCount) =>
        new(
            PatchGapProtocol.PatchEnc005ExperimentId,
            header.RunId,
