    internal static PatchGapToolFile Probe(
        PatchGapExternalToolSpec spec,
        string executablePath,
        PatchGapToolProbeInput provenance)
    {
        ArgumentNullException.ThrowIfNull(spec);
        ArgumentNullException.ThrowIfNull(provenance);
        string fullPath = Path.GetFullPath(executablePath);

        if (!File.Exists(fullPath))
        {
            throw new FileNotFoundException($"Pinned tool '{spec.Id}' was not supplied.", fullPath);
        }

        byte[] bytes = File.ReadAllBytes(fullPath);
        string executableSha256 = Convert.ToHexStringLower(SHA256.HashData(bytes));

        if (!string.Equals(provenance.ObservedVersion, spec.Version, StringComparison.Ordinal) ||
            !string.Equals(provenance.ObservedUpstreamIdentity, spec.UpstreamCommit, StringComparison.Ordinal))
        {
            throw new InvalidDataException(
                $"Pinned tool '{spec.Id}' observed identity " +
                $"{provenance.ObservedVersion}/{provenance.ObservedUpstreamIdentity} " +
                $"does not match frozen {spec.Version}/{spec.UpstreamCommit}.");
        }

        var result = new PatchGapToolFile(
            spec.Id,
            spec.Version,
            spec.UpstreamCommit,
            provenance.ObservedVersion,
            provenance.ObservedUpstreamIdentity,
            spec.CreateCommandTemplate,
            spec.ApplyCommandTemplate,
            provenance.LogicalArtifact.Replace('\\', '/'),
            provenance.BuildCommand,
            provenance.VersionOutput,
            provenance.SourceArchiveSha256.ToLowerInvariant(),
            provenance.ExecutableOrPackageSha256.ToLowerInvariant(),
            executableSha256,
            bytes.LongLength);

        PatchGapToolValidation.Validate([result]);
        return result;
    }
}

