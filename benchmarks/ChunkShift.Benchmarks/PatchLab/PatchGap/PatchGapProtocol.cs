    /// <summary>
    /// Reproduces the PATCH-ENC-004 patchesSha256 contract exactly: ordinally
    /// sort one textual identity line per file and hash the UTF-8 lines.
    /// </summary>
    internal static string PatchSetDigest(IEnumerable<PatchLabFileResult> files)
    {
        string[] lines =
        [
            .. files.Select(static item =>
                    $"{item.Family} {item.Base}->{item.Target} {item.Path} {item.PatchSha256 ?? "-"}")
                .Order(StringComparer.Ordinal),
        ];
        string text = string.Concat(lines.Select(static line => line + "\n"));
        return Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(text)));
    }
