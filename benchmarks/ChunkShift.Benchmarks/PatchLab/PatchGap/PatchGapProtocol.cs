            bytes.LongLength);

    private static JsonElement RequiredArray(JsonElement root, string name)
    {
        if (!root.TryGetProperty(name, out JsonElement value) || value.ValueKind != JsonValueKind.Array)
        {
            throw new InvalidDataException($"PATCH-ENC-005 evidence requires array '{name}'.");
        }

        return value;
    }

    private static string RequiredString(JsonElement root, string name)
    {
        if (!root.TryGetProperty(name, out JsonElement value) || value.ValueKind != JsonValueKind.String)
        {
            throw new InvalidDataException($"PATCH-ENC-005 evidence requires string '{name}'.");
        }

        return value.GetString()!;
    }

    private static string RequiredNonEmptyString(JsonElement root, string name)
    {
        string value = RequiredString(root, name);
        if (string.IsNullOrWhiteSpace(value))
        {
            throw new InvalidDataException($"PATCH-ENC-005 evidence field '{name}' must not be empty.");
        }

        return value;
    }

    private static string? OptionalNonEmptyString(JsonElement root, string name)
    {
        string? value = OptionalString(root, name);
        if (value is not null && string.IsNullOrWhiteSpace(value))
        {
            throw new InvalidDataException($"PATCH-ENC-005 evidence field '{name}' must not be empty.");
        }

        return value;
    }

    private static string? OptionalString(JsonElement root, string name) =>
        root.TryGetProperty(name, out JsonElement value) && value.ValueKind == JsonValueKind.String
            ? value.GetString()
            : null;

    private static JsonElement? OptionalProperty(JsonElement root, string name) =>
        root.TryGetProperty(name, out JsonElement value) ? value : null;

    private static int RequiredInt32(JsonElement root, string name, int minimum)
    {
        if (!root.TryGetProperty(name, out JsonElement value) ||
            value.ValueKind != JsonValueKind.Number ||
            !value.TryGetInt32(out int result) ||
            result < minimum)
        {
            throw new InvalidDataException($"PATCH-ENC-005 evidence field '{name}' must be an integer >= {minimum}.");
        }

        return result;
    }

    private static long RequiredInt64(JsonElement root, string name, long minimum)
    {
        if (!root.TryGetProperty(name, out JsonElement value) ||
            value.ValueKind != JsonValueKind.Number ||
            !value.TryGetInt64(out long result) ||
            result < minimum)
        {
            throw new InvalidDataException($"PATCH-ENC-005 evidence field '{name}' must be an integer >= {minimum}.");
        }

        return result;
    }

    private static int? OptionalInt32(JsonElement root, string name)
    {
        if (!root.TryGetProperty(name, out JsonElement value) || value.ValueKind == JsonValueKind.Null)
        {
            return null;
        }

        if (value.ValueKind != JsonValueKind.Number || !value.TryGetInt32(out int result))
        {
            throw new InvalidDataException($"PATCH-ENC-005 evidence field '{name}' must be integer or null.");
        }

        return result;
    }

    private static long? OptionalInt64(JsonElement root, string name)
    {
        if (!root.TryGetProperty(name, out JsonElement value) || value.ValueKind == JsonValueKind.Null)
        {
            return null;
        }

        if (value.ValueKind != JsonValueKind.Number || !value.TryGetInt64(out long result))
        {
            throw new InvalidDataException($"PATCH-ENC-005 evidence field '{name}' must be integer or null.");
        }

        return result;
    }

    private static bool RequiredBoolean(JsonElement root, string name)
    {
        if (!root.TryGetProperty(name, out JsonElement value) ||
            value.ValueKind is not (JsonValueKind.True or JsonValueKind.False))
        {
            throw new InvalidDataException($"PATCH-ENC-005 evidence field '{name}' must be boolean.");
        }

        return value.GetBoolean();
    }

    private static void RequireHex(string value, int length, string name)
    {
        if (value.Length != length || !value.All(static c => char.IsAsciiHexDigit(c)))
        {
            throw new InvalidDataException(
                $"PATCH-ENC-005 evidence field '{name}' must be {length} hexadecimal characters.");
        }
    }

