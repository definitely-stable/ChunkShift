using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using ChunkShift.Benchmarks.Lab.Prefreeze;

namespace ChunkShift.Benchmarks.Tests.Prefreeze;

public class CorpusLockTests
{
    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web);

    [Fact]
    public void ValidManifestPassesValidationOnly()
    {
        using var scope = new TempDirectory();
        string manifestPath = PrefreezeRunnerTests.WriteFamilies(
            scope.Path, null, ("game-a", 5, RealCorpus.Calibration), ("game-b", 3, RealCorpus.Holdout), ("pair", 2, RealCorpus.Holdout));
        var output = new StringWriter();

        Assert.Equal(0, CorpusLock.Run(["--real", manifestPath], output));

        RealCorpusValidation validation = JsonSerializer.Deserialize<RealCorpusValidation>(output.ToString(), Json)!;
        Assert.Equal(Sha256(manifestPath), validation.ManifestSha256);
        Assert.Null(validation.ExperimentPlanSha256);
        Assert.Equal(3, validation.Families);
        Assert.Equal(1, validation.CalibrationFamilies);
        Assert.Equal(2, validation.HoldoutFamilies);
        Assert.Equal(1, validation.EligibleCalibrationFamilies);
        Assert.Equal(1, validation.EligibleHoldoutFamilies);
        Assert.True(validation.SelectionPossible);
        Assert.Equal(["pair"], validation.PairOnlyFamilies);
        Assert.Equal(["game-b"], validation.ShortHistoryFamilies);
        Assert.Contains(validation.Warnings, static warning => warning.StartsWith("pair-only", StringComparison.Ordinal));
    }

    [Fact]
    public void LockIsReproducibleAndHoldsOnlyMetadata()
    {
        using var scope = new TempDirectory();
        string manifestPath = PrefreezeRunnerTests.WriteFamilies(
            scope.Path, null, ("game-a", 5, RealCorpus.Calibration), ("game-b", 3, RealCorpus.Holdout));
        string planPath = CheckedInPlan();
        string first = Path.Combine(scope.Path, "lock-1.json");
        string second = Path.Combine(scope.Path, "lock-2.json");

        Assert.Equal(0, CorpusLock.Run(["--real", manifestPath, "--plan", planPath, "--lock-output", first], TextWriter.Null));
        Assert.Equal(0, CorpusLock.Run(["--real", manifestPath, "--plan", planPath, "--lock-output", second], TextWriter.Null));

        byte[] bytes = File.ReadAllBytes(first);
        Assert.Equal(bytes, File.ReadAllBytes(second));

        RealCorpusLock corpusLock = JsonSerializer.Deserialize<RealCorpusLock>(bytes, Json)!;
        Assert.Equal(
            new RealCorpusLock(1, Sha256(manifestPath), Sha256(planPath), CorpusLock.ProtocolBaseline, 1, 1, true),
            corpusLock);

        // Exactly the lock fields: no paths, payload content or measured results.
        using JsonDocument document = JsonDocument.Parse(bytes);
        Assert.Equal(
            ["schemaVersion", "manifestSha256", "experimentPlanSha256", "protocolBaseline",
             "eligibleCalibrationFamilies", "eligibleHoldoutFamilies", "selectionPossible"],
            document.RootElement.EnumerateObject().Select(static property => property.Name));
        string text = Encoding.UTF8.GetString(bytes);
        Assert.DoesNotContain(scope.Path, text, StringComparison.Ordinal);
        Assert.DoesNotContain("\r", text, StringComparison.Ordinal);
    }

    [Fact]
    public void OneManifestByteChangesTheLockDigest()
    {
        using var scope = new TempDirectory();
        string manifestPath = PrefreezeRunnerTests.WriteFamilies(scope.Path, null, ("game", 3, RealCorpus.Holdout));
        string planPath = CheckedInPlan();
        RealCorpusLock before = CorpusLock.CreateLock(CorpusLock.Validate(manifestPath, planPath));

        // Still a valid manifest: only the provenance text differs by one byte.
        string manifest = File.ReadAllText(manifestPath);
        File.WriteAllText(manifestPath, manifest.Replace("generated by test", "generated by tesT", StringComparison.Ordinal));
        RealCorpusLock after = CorpusLock.CreateLock(CorpusLock.Validate(manifestPath, planPath));

        Assert.NotEqual(before.ManifestSha256, after.ManifestSha256);
        Assert.Equal(Sha256(manifestPath), after.ManifestSha256);
        Assert.Equal(before.ExperimentPlanSha256, after.ExperimentPlanSha256);
        Assert.NotEqual(CorpusLock.Serialize(before), CorpusLock.Serialize(after));
    }

    [Fact]
    public void ChangingThePlanChangesThePlanDigest()
    {
        using var scope = new TempDirectory();
        string manifestPath = PrefreezeRunnerTests.WriteFamilies(scope.Path, null, ("game", 3, RealCorpus.Holdout));
        string planPath = Path.Combine(scope.Path, "prefreeze.v1.json");
        File.Copy(CheckedInPlan(), planPath);
        RealCorpusLock before = CorpusLock.CreateLock(CorpusLock.Validate(manifestPath, planPath));

        File.AppendAllText(planPath, "\n");
        RealCorpusLock after = CorpusLock.CreateLock(CorpusLock.Validate(manifestPath, planPath));

        Assert.Equal(Sha256(CheckedInPlan()), before.ExperimentPlanSha256);
        Assert.NotEqual(before.ExperimentPlanSha256, after.ExperimentPlanSha256);
        Assert.Equal(before.ManifestSha256, after.ManifestSha256);
    }

    [Fact]
    public void PairOnlyHoldoutLocksWithSelectionImpossible()
    {
        using var scope = new TempDirectory();
        string manifestPath = PrefreezeRunnerTests.WriteFamilies(
            scope.Path, null, ("game-a", 5, RealCorpus.Calibration), ("game-b", 2, RealCorpus.Holdout));

        RealCorpusLock corpusLock = CorpusLock.CreateLock(CorpusLock.Validate(manifestPath, CheckedInPlan()));

        Assert.Equal(1, corpusLock.EligibleCalibrationFamilies);
        Assert.Equal(0, corpusLock.EligibleHoldoutFamilies);
        Assert.False(corpusLock.SelectionPossible);
    }

    [Fact]
    public void EligibleCalibrationAndHoldoutLockWithSelectionPossible()
    {
        using var scope = new TempDirectory();
        string manifestPath = PrefreezeRunnerTests.WriteFamilies(
            scope.Path, null, ("game-a", 3, RealCorpus.Calibration), ("game-b", 5, RealCorpus.Holdout));

        RealCorpusLock corpusLock = CorpusLock.CreateLock(CorpusLock.Validate(manifestPath, CheckedInPlan()));

        Assert.Equal(1, corpusLock.EligibleCalibrationFamilies);
        Assert.Equal(1, corpusLock.EligibleHoldoutFamilies);
        Assert.True(corpusLock.SelectionPossible);
    }

    [Theory]
    [InlineData("corrupt-digest")]
    [InlineData("no-split")]
    [InlineData("uppercase-digest")]
    [InlineData("short-digest")]
    [InlineData("duplicate-version")]
    [InlineData("empty-version")]
    [InlineData("empty-path")]
    [InlineData("empty-id")]
    public void MalformedManifestIsRejectedAndNoLockIsWritten(string defect)
    {
        using var scope = new TempDirectory();
        string manifestPath = PrefreezeRunnerTests.WriteFamilies(scope.Path, defect, ("game", 3, RealCorpus.Holdout));
        string lockPath = Path.Combine(scope.Path, "corpus-lock.json");

        Assert.Throws<InvalidOperationException>(() =>
            CorpusLock.Run(["--real", manifestPath, "--plan", CheckedInPlan(), "--lock-output", lockPath], TextWriter.Null));
        Assert.False(File.Exists(lockPath));
    }

    [Fact]
    public void ValidationOnlyNeverChunks()
    {
        using var scope = new TempDirectory();
        string manifestPath = PrefreezeRunnerTests.WriteFamilies(scope.Path, null, ("game", 3, RealCorpus.Holdout));

        // A target no Gear candidate accepts: any chunk comparison would throw.
        PrefreezePlan plan = PrefreezeRunnerTests.SmallPlan();
        plan = plan with { Lanes = [plan.Lanes[0] with { Targets = [3] }] };
        string planPath = Path.Combine(scope.Path, "plan.json");
        File.WriteAllText(planPath, JsonSerializer.Serialize(plan, Json));
        Assert.ThrowsAny<Exception>(() => PrefreezeRunner.Execute(plan, null, synthetic: false, manifestPath, TextWriter.Null));

        string[] before = Files(scope.Path);
        string lockPath = Path.Combine(scope.Path, "corpus-lock.json");
        string resultPath = Path.Combine(scope.Path, "result.json");
        var output = new StringWriter();

        Assert.Equal(0, CorpusLock.Run(
            ["--real", manifestPath, "--plan", planPath, "--lock-output", lockPath, "--output", resultPath], output));

        Assert.Equal([.. before.Append(lockPath).Order(StringComparer.Ordinal)], Files(scope.Path));
        using JsonDocument document = JsonDocument.Parse(output.ToString());
        Assert.False(document.RootElement.TryGetProperty("rows", out _));
        Assert.False(document.RootElement.TryGetProperty("divergence", out _));
        Assert.False(document.RootElement.TryGetProperty("families", out JsonElement families) && families.ValueKind == JsonValueKind.Array);
    }

    [Fact]
    public void LockNeedsThePlan()
    {
        using var scope = new TempDirectory();
        string manifestPath = PrefreezeRunnerTests.WriteFamilies(scope.Path, null, ("game", 3, RealCorpus.Holdout));
        string lockPath = Path.Combine(scope.Path, "corpus-lock.json");

        Assert.Equal(2, CorpusLock.Run(["--real", manifestPath, "--lock-output", lockPath], TextWriter.Null));
        Assert.False(File.Exists(lockPath));
    }

    private static string CheckedInPlan() =>
        Path.Combine(PrefreezeRunnerTests.RepositoryRoot(), "benchmarks", "experiments", "prefreeze.v1.json");

    private static string Sha256(string path) => Convert.ToHexStringLower(SHA256.HashData(File.ReadAllBytes(path)));

    private static string[] Files(string directory) =>
        [.. Directory.GetFiles(directory, "*", SearchOption.AllDirectories).Order(StringComparer.Ordinal)];

    private sealed class TempDirectory : IDisposable
    {
        public string Path { get; } = Directory.CreateTempSubdirectory("chunkshift-corpus-lock-").FullName;

        public void Dispose() => Directory.Delete(Path, recursive: true);
    }
}
